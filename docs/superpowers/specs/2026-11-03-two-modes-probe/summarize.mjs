// Probe only: turns the result files of one run into results/summary.md.
import fs from "node:fs";

const R = (f) => JSON.parse(fs.readFileSync(`results/${f}`, "utf8"));
const lines = (f) => fs.readFileSync(`results/${f}`, "utf8").trim().split("\n").map((l) => JSON.parse(l));
const cell = (v) => String(v ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ").slice(0, 160);
const out = [];
const md = (s = "") => out.push(s);

const tcp = R("pw-tcp.json").results;
const unix = R("pw-unix.json").results;
const mcp = R("mcp.json");
const matrix = R("matrix.json");
const site = lines("site-log.jsonl");

md("# Two-modes probe: results of one run");
md();
md(`Chromium ${matrix.info.fullVersion} (Debian), Playwright 1.64.1, Playwright MCP 0.0.84. Generated by summarize.mjs.`);
md();
md("## Playwright through the extension (connectOverCDP)");
md();
md("| Case | Expected | Loopback TCP | Unix socket | What Playwright saw (TCP) |");
md("| --- | --- | --- | --- | --- |");
for (const r of tcp) {
  const u = unix.find((x) => x.case === r.case);
  const mark = (x) => (x ? (x.ok ? "pass" : "FAIL") : "-");
  md(`| ${cell(r.case)} | ${r.expect === "refused" ? "refused" : "works"} | ${mark(r)} (${r.ms} ms) | ${mark(u)}${u ? ` (${u.ms} ms)` : ""} | ${cell(r.error !== undefined ? r.error : JSON.stringify(r.detail))} |`);
}
md();
md("## The Playwright MCP through the extension (PLAYWRIGHT_MCP_CDP_ENDPOINT)");
md();
md(`${mcp.tools} tools listed.`);
md();
md("| Tool call | Result | What the MCP answered |");
md("| --- | --- | --- |");
for (const r of mcp.results) md(`| ${r.tool} | ${r.isError ? "error" : "ok"} (${r.ms} ms) | ${cell(r.saw)} |`);
md();
md("## What chrome.debugger allows an extension (the matrix)");
md();
md("| CDP command on a tab session | Result |");
md("| --- | --- |");
for (const r of matrix.page) md(`| ${cell(r.label)} | ${r.ok ? "ok" + (r.note ? ": " + cell(JSON.stringify(r.note)) : "") : "refused: " + cell(r.error)} |`);
md();
md(`Target types that chrome.debugger.getTargets shows: ${matrix.targetTypes.join(", ")}. Attach to a chrome:// tab: ${matrix.chromePage}.`);
md();
md("## What the site saw");
md();
const reports = site.filter((x) => x.t === "report");
const base = reports[0];
const baseGlobals = new Set(base.globals);
md("The first row is the baseline: a tab that the extension opened, with no debugger attached. `new globals` lists window properties that the baseline page did not have.");
md();
md("| Time | Report | Page | webdriver | innerHeight | resize events | Runtime tell | hasFocus | visibility | trusted events | untrusted events | new globals |");
md("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
for (const r of reports) {
  const extra = r.globals.filter((g) => !baseGlobals.has(g));
  md(`| ${r.at.slice(11, 19)} | ${r.kind} | ${cell(r.url.replace("http://", ""))} | ${r.webdriver} | ${r.innerHeight} | ${r.resize} | ${r.runtimeTell} | ${r.hasFocus} | ${r.visibility} | ${r.trusted.join(" ")} | ${r.untrusted.join(" ")} | ${cell(extra.join(" "))} |`);
}
md();
md("## Navigation headers, by how the navigation started");
md();
md("| Request | Sec-Fetch-Site | Sec-Fetch-User |");
md("| --- | --- | --- |");
const seen = new Set();
for (const r of site.filter((x) => x.t === "req" && x.fetch.dest === "document")) {
  const nav = /nav=([a-z_]+)/.exec(r.path);
  const key = nav ? nav[1] : r.host + r.path;
  if (!nav || seen.has(key)) continue;
  seen.add(key);
  md(`| ${key} | ${r.fetch.site} | ${r.fetch.user || "(none)"} |`);
}
const offList = site.filter((x) => x.t === "req" && x.host === "b.localhost").length;
md();
md(`Requests that reached the off-list host b.localhost in the whole run: ${offList}.`);
fs.writeFileSync("results/summary.md", out.join("\n") + "\n");
// Compact copies to keep in git: the raw logs (every global name of every report,
// every CDP message) are large and stay out of the repo (results/.gitignore).
const compact = site.map((x) => (x.t === "report" ? { ...x, globals: undefined, newGlobals: x.globals.filter((g) => !baseGlobals.has(g)) } : x));
fs.writeFileSync("results/site-log.compact.jsonl", compact.map((x) => JSON.stringify(x)).join("\n") + "\n");
const relay = lines("relay-log.jsonl");
const methods = {};
for (const x of relay.filter((x) => x.t === "cdp")) methods[x.method] = (methods[x.method] || 0) + 1;
fs.writeFileSync("results/relay-events.json", JSON.stringify({ cdpMethodCounts: methods, events: relay.filter((x) => x.t !== "cdp") }, null, 2) + "\n");
console.log("wrote results/summary.md");
